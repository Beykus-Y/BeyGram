package com.beykus.beygram.deeplink

import com.beykus.beygram.domain.model.TelegramProxyDraft
import com.beykus.beygram.domain.model.TelegramProxyKind

/**
 * A validated Telegram link from another application.
 *
 * Parsing is deliberately independent of Android and TDLib: it only classifies a string and never performs a lookup,
 * joins a chat or opens an arbitrary URI. The router then maps the result to a single app action.
 */
internal sealed interface TelegramDeepLink {
    data class Username(val username: String) : TelegramDeepLink {
        override fun toString(): String = "Username($username)"
    }

    data class Phone(val phone: String) : TelegramDeepLink {
        override fun toString(): String = "Phone(***)"
    }

    /** tg://user links are generated by Telegram itself for mentions and inline buttons. */
    data class UserId(val userId: Long) : TelegramDeepLink {
        override fun toString(): String = "UserId($userId)"
    }

    /** A bot link with an optional /start payload. The payload is never sent automatically. */
    data class Bot(val username: String, val startParameter: String?) : TelegramDeepLink {
        override fun toString(): String = "Bot($username)"
    }

    /** Canonical invite link, e.g. https://t.me/+AbCdEf. */
    data class Invite(val url: String) : TelegramDeepLink

    /** Canonical message link, including private /c/ links. */
    data class Message(val url: String, val messageId: Long) : TelegramDeepLink

    data class Proxy(val draft: TelegramProxyDraft) : TelegramDeepLink {
        override fun toString(): String = "Proxy(${draft.kind}:${draft.server}:${draft.port})"
    }

    /**
     * QR-login links are recognized only so they can be ignored. The token is not retained: it must never reach
     * pending-link storage, a log or a normal chat lookup.
     */
    data object Login : TelegramDeepLink
}

/** Pure, fail-closed parser for https://t.me, https://telegram.me and tg:// links. */
internal object TelegramDeepLinkParser {
    private val HTTPS_HOSTS = setOf("t.me", "telegram.me")
    private val USERNAME = Regex("[A-Za-z][A-Za-z0-9_]{0,63}")
    private val INVITE_HASH = Regex("[A-Za-z0-9_-]{1,256}")
    private val PHONE = Regex("\\+[0-9]{4,16}")
    private val PROXY_SECRET = Regex("[A-Za-z0-9_+/=.-]{1,1024}")
    private val PROXY_CREDENTIAL = Regex("[^\\u0000-\\u0020\\u007f]{0,255}")
    private val HOST = Regex("[A-Za-z0-9._:\\[\\]-]{1,253}")

    // First path segment of t.me links that mean an action, never a public username.
    private val RESERVED_HTTPS_PATH = setOf(
        "c", "joinchat", "proxy", "socks", "login", "addstickers", "addemoji", "addtheme", "addlist",
        "setlanguage", "share", "iv", "contact", "s", "bg", "invoice", "giftcode", "boost"
    )

    /** Returns null for malformed, unsupported or ambiguous links. Never throws for untrusted input. */
    fun parse(raw: String?): TelegramDeepLink? {
        if (raw.isNullOrEmpty() || raw.length > 2_048) return null
        // An intent data string is a URI, not free text. Whitespace and controls are malformed and may hide a second value.
        if (raw != raw.trim() || raw.any { it.code < 0x20 || it.code == 0x7f || it == ' ' }) return null
        return runCatching {
            when {
                raw.startsWith("https://", ignoreCase = true) -> parseHttps(raw)
                raw.startsWith("tg://", ignoreCase = true) -> parseTelegram(raw)
                else -> null
            }
        }.getOrNull()
    }

    private fun parseHttps(raw: String): TelegramDeepLink? {
        val rest = raw.substringAfter("://", missingDelimiterValue = "")
        if (rest.isEmpty()) return null
        val authorityEnd = rest.indexOfAny(charArrayOf('/', '?', '#')).let { if (it < 0) rest.length else it }
        val authority = rest.substring(0, authorityEnd)
        if (authority.any { it == '@' || it == ':' } || authority.lowercase() !in HTTPS_HOSTS) return null

        val target = rest.substring(authorityEnd)
        val withoutFragment = target.substringBefore('#')
        val path = withoutFragment.substringBefore('?')
        val query = if ('?' in withoutFragment) withoutFragment.substringAfter('?') else ""
        val queryValues = parseQuery(query) ?: return null

        if (!path.startsWith('/')) return null
        val withoutTrailingSlash = path.removeSuffix("/")
        if (withoutTrailingSlash.isEmpty()) return null
        val segments = withoutTrailingSlash.removePrefix("/").split('/')
        if (segments.any { it.isEmpty() }) return null

        return when {
            segments.size == 1 && segments[0].startsWith("+") -> parsePlusPath(segments[0])
            segments[0].equals("c", ignoreCase = true) -> parsePrivateMessage(segments, queryValues)
            segments[0].equals("joinchat", ignoreCase = true) -> parseHttpsInvite(segments)
            segments[0].equals("proxy", ignoreCase = true) ->
                parseProxy(segments, queryValues, TelegramProxyKind.MTPROTO)
            segments[0].equals("socks", ignoreCase = true) ->
                parseProxy(segments, queryValues, TelegramProxyKind.SOCKS5)
            segments[0].equals("login", ignoreCase = true) -> null
            segments[0].lowercase() in RESERVED_HTTPS_PATH -> null
            else -> parseHttpsChat(segments, queryValues)
        }
    }

    /** t.me/+79991234567 is a phone lookup; t.me/+AbCdEf is the short invite form. */
    private fun parsePlusPath(segment: String): TelegramDeepLink? {
        val value = segment.removePrefix("+")
        if (value.isEmpty()) return null
        val phone = normalizePhone(value)
        if (phone != null) return TelegramDeepLink.Phone(phone)
        if (!INVITE_HASH.matches(value)) return null
        return TelegramDeepLink.Invite(inviteUrl(value))
    }

    private fun parseHttpsInvite(segments: List<String>): TelegramDeepLink? {
        if (segments.size != 2) return null
        val hash = segments[1]
        if (!INVITE_HASH.matches(hash)) return null
        return TelegramDeepLink.Invite(inviteUrl(hash))
    }

    private fun parseHttpsChat(segments: List<String>, query: Map<String, String>): TelegramDeepLink? {
        val username = segments[0]
        if (!USERNAME.matches(username)) return null
        return when (segments.size) {
            1 -> parseChatQuery(username, query)
            2 -> parseMessageId(segments[1])?.let { messageId ->
                TelegramDeepLink.Message(messageUrl(username, messageId, query["thread"]), messageId)
            }
            3 -> {
                // t.me/<username>/<topic>/<message>
                parseId(segments[1]) ?: return null
                val messageId = parseMessageId(segments[2]) ?: return null
                TelegramDeepLink.Message(
                    "https://t.me/$username/${segments[1]}/${segments[2]}",
                    messageId
                )
            }
            else -> null
        }
    }

    private fun parseChatQuery(username: String, query: Map<String, String>): TelegramDeepLink? {
        val post = query["post"]
        if (post != null) {
            val messageId = parseMessageId(post) ?: return null
            return TelegramDeepLink.Message(messageUrl(username, messageId, query["thread"]), messageId)
        }
        val start = query["start"] ?: query["startgroup"]
        if (start != null) {
            if (!validStartParameter(start)) return null
            return TelegramDeepLink.Bot(username, start)
        }
        return TelegramDeepLink.Username(username)
    }

    private fun parsePrivateMessage(segments: List<String>, query: Map<String, String>): TelegramDeepLink? {
        // t.me/c/<internal>/<message> or t.me/c/<internal>/<topic>/<message>
        if (segments.size !in 3..4) return null
        val internalId = parseId(segments[1]) ?: return null
        val messageId = parseMessageId(segments.last()) ?: return null
        val topicId = if (segments.size == 4) parseId(segments[2]) ?: return null else null
        val url = buildString {
            append("https://t.me/c/").append(internalId).append('/')
            if (topicId != null) append(topicId).append('/')
            append(messageId)
            query["thread"]?.let { thread -> if (parseId(thread) != null) append("?thread=").append(thread) }
        }
        return TelegramDeepLink.Message(url, messageId)
    }

    private fun parseTelegram(raw: String): TelegramDeepLink? {
        val rest = raw.substringAfter("://", missingDelimiterValue = "")
        if (rest.isEmpty()) return null
        val actionEnd = rest.indexOfAny(charArrayOf('/', '?', '#')).let { if (it < 0) rest.length else it }
        val action = rest.substring(0, actionEnd).lowercase()
        val afterAction = rest.substring(actionEnd)
        if (afterAction.startsWith("/") && afterAction.length > 1) return null
        val withoutFragment = afterAction.substringBefore('#')
        val query = if ('?' in withoutFragment) withoutFragment.substringAfter('?') else ""
        val values = parseQuery(query) ?: return null
        return when (action) {
            "resolve" -> parseResolve(values)
            "join" -> parseTelegramJoin(values)
            "proxy" -> parseProxy(emptyList(), values, TelegramProxyKind.MTPROTO)
            "socks" -> parseProxy(emptyList(), values, TelegramProxyKind.SOCKS5)
            "login" -> TelegramDeepLink.Login
            "user" -> parseUserId(values)
            else -> null
        }
    }

    private fun parseUserId(query: Map<String, String>): TelegramDeepLink? {
        val id = query["id"]?.toLongOrNull()?.takeIf { it > 0L } ?: return null
        return TelegramDeepLink.UserId(id)
    }

    private fun parseResolve(query: Map<String, String>): TelegramDeepLink? {
        val phone = query["phone"]
        val domain = query["domain"]
        if (phone != null && domain != null) return null
        if (phone != null) {
            val normalized = normalizePhone(phone) ?: return null
            return TelegramDeepLink.Phone(normalized)
        }
        if (domain == null || !USERNAME.matches(domain)) return null
        val post = query["post"]
        return if (post != null) {
            val messageId = parseMessageId(post) ?: return null
            TelegramDeepLink.Message(messageUrl(domain, messageId, query["thread"]), messageId)
        } else {
            val start = query["start"] ?: query["startgroup"]
            if (start != null) {
                if (!validStartParameter(start)) return null
                TelegramDeepLink.Bot(domain, start)
            } else {
                TelegramDeepLink.Username(domain)
            }
        }
    }

    private fun parseTelegramJoin(query: Map<String, String>): TelegramDeepLink? {
        // Extra tg://join parameters are ignored; only the invite hash determines the target.
        val invite = query["invite"] ?: return null
        if (!INVITE_HASH.matches(invite)) return null
        return TelegramDeepLink.Invite(inviteUrl(invite))
    }

    private fun parseProxy(
        segments: List<String>,
        query: Map<String, String>,
        kind: TelegramProxyKind
    ): TelegramDeepLink? {
        if (segments.size > 1) return null
        val server = query["server"] ?: return null
        if (!HOST.matches(server)) return null
        val port = query["port"]?.toIntOrNull() ?: return null
        if (port !in 1..65_535) return null
        return when (kind) {
            TelegramProxyKind.MTPROTO -> {
                val secret = query["secret"] ?: return null
                if (!PROXY_SECRET.matches(secret)) return null
                TelegramDeepLink.Proxy(
                    TelegramProxyDraft(TelegramProxyKind.MTPROTO, server, port, secret = secret)
                )
            }
            TelegramProxyKind.SOCKS5 -> {
                val username = query["user"] ?: ""
                val password = query["pass"] ?: ""
                if (!PROXY_CREDENTIAL.matches(username) || !PROXY_CREDENTIAL.matches(password)) return null
                TelegramDeepLink.Proxy(
                    TelegramProxyDraft(TelegramProxyKind.SOCKS5, server, port, username = username, password = password)
                )
            }
            TelegramProxyKind.HTTP -> null
        }
    }

    private fun parseQuery(query: String): Map<String, String>? {
        if (query.isEmpty()) return emptyMap()
        val result = linkedMapOf<String, String>()
        for (pair in query.split('&')) {
            if (pair.isEmpty()) return null
            val key = pair.substringBefore('=')
            if (key.isEmpty()) return null
            val rawValue = if ('=' in pair) pair.substringAfter('=') else ""
            val value = percentDecode(rawValue) ?: return null
            val normalizedKey = key.lowercase()
            if (result.put(normalizedKey, value) != null) return null
        }
        return result
    }

    private fun percentDecode(value: String): String? {
        val bytes = java.io.ByteArrayOutputStream(value.length)
        var index = 0
        while (index < value.length) {
            val char = value[index]
            if (char == '%') {
                if (index + 2 >= value.length) return null
                val high = value[index + 1].digitToIntOrNull(16) ?: return null
                val low = value[index + 2].digitToIntOrNull(16) ?: return null
                bytes.write((high shl 4) or low)
                index += 3
            } else {
                // Non-ASCII literals and escaped bytes must be decoded together as UTF-8.
                bytes.write(char.toString().toByteArray(Charsets.UTF_8))
                index++
            }
        }
        return bytes.toByteArray().toString(Charsets.UTF_8)
    }

    private fun normalizePhone(value: String): String? {
        val digits = value.removePrefix("+")
        if (digits.length !in 4..16 || digits.any { !it.isDigit() }) return null
        val normalized = "+$digits"
        return normalized.takeIf { PHONE.matches(it) }
    }

    private fun parseMessageId(value: String): Long? =
        value.toLongOrNull()?.takeIf { it in 1..Long.MAX_VALUE }

    private fun parseId(value: String): Long? =
        value.toLongOrNull()?.takeIf { it > 0L }

    private fun validStartParameter(value: String): Boolean =
        value.length <= 128 && value.none { it.code < 0x20 || it.code == 0x7f }

    private fun inviteUrl(hash: String): String = "https://t.me/+$hash"

    private fun messageUrl(username: String, messageId: Long, thread: String?): String = buildString {
        append("https://t.me/").append(username).append('/').append(messageId)
        if (thread != null && parseId(thread) != null) append("?thread=").append(thread)
    }
}

/** Pure mapping from a validated link to the one app action it may start. */
internal sealed interface TelegramDeepLinkRoute {
    data object Ignore : TelegramDeepLinkRoute
    data class Chat(val username: String) : TelegramDeepLinkRoute
    data class Phone(val phone: String) : TelegramDeepLinkRoute
    data class UserId(val userId: Long) : TelegramDeepLinkRoute
    data class Invite(val url: String) : TelegramDeepLinkRoute
    data class Message(val url: String, val messageId: Long) : TelegramDeepLinkRoute
    data class Proxy(val draft: TelegramProxyDraft) : TelegramDeepLinkRoute {
        override fun toString(): String = "Proxy(${draft.kind}:${draft.server}:${draft.port})"
    }
}

internal object TelegramDeepLinkRouter {
    fun route(link: TelegramDeepLink?): TelegramDeepLinkRoute = when (link) {
        null, TelegramDeepLink.Login -> TelegramDeepLinkRoute.Ignore
        is TelegramDeepLink.Username -> TelegramDeepLinkRoute.Chat(link.username)
        // A bot is still a public chat. Its /start payload is intentionally not sent without a user action.
        is TelegramDeepLink.Bot -> TelegramDeepLinkRoute.Chat(link.username)
        is TelegramDeepLink.Phone -> TelegramDeepLinkRoute.Phone(link.phone)
        is TelegramDeepLink.UserId -> TelegramDeepLinkRoute.UserId(link.userId)
        is TelegramDeepLink.Invite -> TelegramDeepLinkRoute.Invite(link.url)
        is TelegramDeepLink.Message -> TelegramDeepLinkRoute.Message(link.url, link.messageId)
        is TelegramDeepLink.Proxy -> TelegramDeepLinkRoute.Proxy(link.draft)
    }
}

/** True when the link needs an app lookup or a confirmation dialog. */
internal fun TelegramDeepLink.isActionable(): Boolean =
    TelegramDeepLinkRouter.route(this) !is TelegramDeepLinkRoute.Ignore
